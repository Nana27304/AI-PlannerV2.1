def load(name, default):
    if os.path.exists(name):
        try:
            with open(name) as f:
                return json.load(f)
        except:
            return default
    return default
def save(name, data):
    with open(name, "w") as f:
        json.dump(data, f)
def hash_pw(pw):
    return hashlib.sha256(pw.encode()).hexdigest()
def make_pdf_bytes(title, body_text):
    doc = pymupdf.open()
    page = doc.new_page(width=595, height=842)
    y = 60
    page.insert_text((50, y), "AI PLANNER- Gyasi Emmanuel", fontsize=14, color=(0,0,0.6))
    y += 30
    page.insert_text((50, y), title[:80], fontsize=12, color=(0,0,0))
    y += 30
    words = body_text.replace("\n"," ").split(" ")
    line = ""
    for w in words:
        if len(line + " " + w) > 85:
            page.insert_text((50, y), line, fontsize=10)
            y += 16
            line = w
            if y > 780:
                page = doc.new_page(width=595, height=842)
                y = 60
        else:
            line = line + " " + w if line else w
    if line:
        page.insert_text((50, y), line, fontsize=10)
    page.insert_text((50, 800), "Generated by AI Planner Ghana - Gyasi Emmanuel, KNUST", fontsize=8, color=(0.5,0.5,0.5))
    buf = io.BytesIO()
    doc.save(buf)
    doc.close()
    buf.seek(0)
    return buf.getvalue()
def extract_text_from_pdf(uploaded_file):
    try:
        doc = pymupdf.open(stream=uploaded_file.read(), filetype="pdf")
        text = ""
        for page in doc:
            text += page.get_text() + "\n"
        return text[:15000]
    except Exception as e:
        return "Error: " + str(e)
def extract_text_from_docx(uploaded_file):
    try:
        d = docx.Document(uploaded_file)
        text = ""
        for para in d.paragraphs:
            text += para.text + "\n"
        for table in d.tables:
            for row in table.rows:
                for cell in row.cells:
                    text += cell.text + " "
                text += "\n"
        return text[:15000]
    except Exception as e:
        return "Error: " + str(e)
